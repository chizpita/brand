#!/usr/bin/env python3
"""Write tokens/ (colors + type as JSON and CSS variables) from one table.

CMYK values are naive RGB->CMYK conversions for briefing a printer; always
proof on the actual stock (kraft shifts everything warmer and darker).
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

COLORS = [
    # token, name, hex, role
    ('roast', 'Roast', '#2A1A0F', 'Ink: wordmark, outlines, body text'),
    ('spark-gold', 'Spark Gold', '#F2A230', 'The spark on the i, rays, heart divider, accents'),
    ('cheese', 'Cheese', '#F2B53A', 'The cheese drip off the A; warm highlights'),
    ('crust', 'Crust', '#E3913A', 'Toasted crust orange (matches the illustration)'),
    ('cream', 'Cream', '#FFF3DC', 'Badge and icon ground; light text on dark'),
    ('paper', 'Warm White', '#FFFCF6', 'Page background'),
    ('olive', 'Olive', '#4E6B2C', 'Secondary accent for green flavors (e.g. Chilaquil Verde)'),
    ('roast-soft', 'Roast 70', '#6E5A49', 'Secondary text'),
]


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def cmyk(h):
    r, g, b = (v / 255 for v in rgb(h))
    k = 1 - max(r, g, b)
    if k >= 1:
        return (0, 0, 0, 100)
    c, m, y = ((1 - v - k) / (1 - k) for v in (r, g, b))
    return tuple(round(v * 100) for v in (c, m, y, k))


def lum(h):
    def ch(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(v) for v in rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


TYPE = {
    'display': {'family': 'Titan One', 'fallback': "'Titan One', 'Arial Rounded MT Bold', system-ui, sans-serif",
                'weights': [400], 'license': 'OFL-1.1', 'source': 'https://fonts.google.com/specimen/Titan+One',
                'use': 'Headlines, short punchy lines, prices. Never for paragraphs. ALL CAPS or Title Case.'},
    'text': {'family': 'Figtree', 'fallback': "'Figtree', system-ui, -apple-system, 'Segoe UI', sans-serif",
             'weights': [400, 500, 600, 700, 800], 'license': 'OFL-1.1',
             'source': 'https://fonts.google.com/specimen/Figtree',
             'use': 'Everything else: UI, body, menus, order pages. Covers accented names such as El Clásico.'},
}


def main():
    os.makedirs(os.path.join(ROOT, 'tokens'), exist_ok=True)
    tokens = {'$schema': 'https://design-tokens.github.io/community-group/format/',
              'version': '3.0.0', 'color': {}, 'font': {}}
    for t, name, h, role in COLORS:
        tokens['color'][t] = {'$type': 'color', '$value': h, '$description': role,
                              'name': name, 'rgb': rgb(h), 'cmyk_approx': cmyk(h)}
    for t, v in TYPE.items():
        tokens['font'][t] = {'$type': 'fontFamily', '$value': v['fallback'], **v}
    pairs = [(a, b) for a in ('roast', 'olive', 'roast-soft', 'crust') for b in ('paper', 'cream')]
    pairs += [('cream', 'roast'), ('spark-gold', 'roast'), ('roast', 'spark-gold')]
    tokens['contrast'] = {f'{a}-on-{b}': round(contrast(dict((c[0], c[2]) for c in COLORS)[a],
                                                         dict((c[0], c[2]) for c in COLORS)[b]), 2)
                          for a, b in pairs}
    with open(os.path.join(ROOT, 'tokens', 'tokens.json'), 'w') as f:
        json.dump(tokens, f, indent=2, ensure_ascii=False)
        f.write('\n')
    css = ['/* Chizpita brand tokens v3.0.0 - generated by tools/build_tokens.py */',
           "@import url('https://fonts.googleapis.com/css2?family=Titan+One&family=Figtree:wght@400;500;600;700;800&display=swap');",
           ':root {']
    for t, name, h, role in COLORS:
        css.append(f'  --chz-{t}: {h}; /* {name}: {role} */')
    css.append(f"  --chz-font-display: {TYPE['display']['fallback']};")
    css.append(f"  --chz-font-text: {TYPE['text']['fallback']};")
    css.append('  --chz-line: 0.03125em; /* outline weight = 1/32 of the mark width */')
    css.append('}')
    with open(os.path.join(ROOT, 'tokens', 'brand.css'), 'w') as f:
        f.write('\n'.join(css) + '\n')
    for k, v in tokens['contrast'].items():
        print(f'{k:28s} {v:5.2f}')


if __name__ == '__main__':
    main()
